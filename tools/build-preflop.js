/* Builds js/preflop.js: equity of each of the 169 starting hands against
 * 1..8 random opponents (Monte Carlo, TRIALS deals each).
 *     node tools/build-preflop.js [trials]
 * Don't hand-edit js/preflop.js; rerun this. */
const fs = require("fs");
const path = require("path");
const P = require("../js/poker.js");
const TRIALS = +process.argv[2] || 30000;

const table = [];
const t0 = Date.now();
P.CLASSES.forEach((cls, idx) => {
  const r1 = P.RANKS.indexOf(cls[0]), r2 = P.RANKS.indexOf(cls[1]);
  const suited = cls[2] === "s";
  const hero = [P.makeCard(r1, 3), P.makeCard(r2, suited ? 3 : 2)];
  const row = [];
  for (let n = 1; n <= 8; n++) {
    const r = P.equity({ hero, opponents: n, trials: TRIALS, seed: idx * 31 + n, exactLimit: 0 });
    row.push(Math.round(r.equity * 10000) / 10000);
  }
  table.push(row);
});
const out = `/* GENERATED by tools/build-preflop.js (${TRIALS} deals per cell) — don't hand-edit.
 * PREFLOP[i][n-1] = equity of starting-hand class Poker.CLASSES[i] against n random hands. */
(function (root) {
  const PREFLOP = ${JSON.stringify(table)};
  if (typeof module !== "undefined" && module.exports) module.exports = PREFLOP;
  else root.PREFLOP = PREFLOP;
})(typeof self !== "undefined" ? self : this);
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "preflop.js"), out);
console.log("wrote js/preflop.js in", ((Date.now() - t0) / 1000).toFixed(1), "s");
